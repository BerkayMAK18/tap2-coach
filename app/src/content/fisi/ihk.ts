import type { CardQuestion } from "../schema";

/** Aufgabe im Prüfungsstil: [Aufgabentext mit Operator, Punkte, optional abweichende Musterlösung als Aspekte]. */
type Spec = [aufgabe: string, punkte: number, aspekte?: string[]];

const HINT: Record<string, string> = {
  Nennen: "Stichworte genügen",
  Beschreiben: "zusammenhängend und vollständig",
  Erläutern: "mit Begründung oder Beispiel",
  Begründen: "mit nachvollziehbarer Begründung",
  Beurteilen: "mit eigenem, begründetem Urteil",
  Unterscheiden: "Unterschiede klar benennen",
  Berechnen: "mit Rechenweg und Ergebnis",
};

/** Zerlegt eine Fließtext-Musterlösung in einzelne bewertbare Aspekte (Sätze und Strichpunkt-Teile). */
const aspekte = (a: string) => a.split(/(?<=[.!?])\s+|;\s+/).map((s) => s.trim()).filter(Boolean);

/** Überträgt eine Wissenskarte in den IHK-Stil: Operator, Punkte, Aspekte der Musterlösung, Erwartungshorizont. */
export function ihk(base: CardQuestion[], specs: Spec[]): CardQuestion[] {
  if (base.length !== specs.length) throw new Error(`IHK-Aufgaben passen nicht: ${base.length} Karten, ${specs.length} Aufgaben`);
  return base.map((c, i) => {
    const [aufgabe, punkte, eigene] = specs[i];
    const op = aufgabe.match(/\b(Nennen|Beschreiben|Erläutern|Begründen|Beurteilen|Unterscheiden|Berechnen)\b/)?.[1] ?? "Erläutern";
    const teile = eigene ?? aspekte(c.a);
    return {
      ...c,
      q: `${aufgabe} (${punkte} P.)`,
      a: teile.map((t) => "• " + t).join("\n"),
      note: `Erwartungshorizont: ${punkte} P., je zutreffendem Aspekt 1 P. Operator „${op}“: ${HINT[op]}.`,
    };
  });
}

